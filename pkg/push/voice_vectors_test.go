package push

import (
	"encoding/hex"
	"encoding/json"
	"os"
	"strings"
	"testing"
	"time"
)

// The Android app derives Moa-Voice and opens call envelopes itself; these
// vectors pin both to what the server derives and seals. Separate from
// vectors.json so a voice change never rewrites the relay's file.
const voiceVectorsPath = "../../relay/test/voice-vectors.json"

type voiceVectorFile struct {
	Note   string `json:"note"`
	Device struct {
		S string `json:"S"`
		// VoiceKey is VoiceAuthKey(S), hex.
		VoiceKey string `json:"voice_key"`
		// DeviceID is a sample id; Header is the full Authorization value.
		DeviceID string `json:"device_id"`
		Header   string `json:"header"`
	} `json:"device"`
	Call struct {
		Now       int64    `json:"now"`
		Invite    string   `json:"inv"`
		Exp       int64    `json:"exp"`
		Name      string   `json:"name"`
		Session   string   `json:"session"`
		Plaintext string   `json:"plaintext"`
		Envelope  Envelope `json:"envelope"`
	} `json:"call"`
}

func buildVoiceVectors(t *testing.T) voiceVectorFile {
	t.Helper()
	var v voiceVectorFile
	v.Note = "Generated by pkg/push voice_vectors_test.go (go test ./pkg/push -run TestVoiceVectors -update-vectors). Moa-Voice and the k:\"call\" envelope for the Android app. Binary values are b64u unless named hex."
	secret := seq(0x00, 32)
	keys, err := DeriveDeviceKeys(secret)
	if err != nil {
		t.Fatal(err)
	}
	vk, err := VoiceAuthKey(secret)
	if err != nil {
		t.Fatal(err)
	}
	v.Device.S = b64u.EncodeToString(secret)
	v.Device.VoiceKey = hex.EncodeToString(vk)
	v.Device.DeviceID = "dev_0123456789ab"
	v.Device.Header = "Moa-Voice " + v.Device.DeviceID + "." + b64u.EncodeToString(vk)

	now := time.Unix(1790000000, 0)
	exp := now.Add(45 * time.Second)
	n := Notification{
		Title: "Moa", Body: "Moa is calling", SessionID: "sess_1", Tag: "req:sess_1",
		Kind: KindCall, Level: LevelUrgent,
		Call: &CallInvite{ID: "0f8fad5b-d9cb-469f-a165-70867728950e", Expires: exp},
	}
	id := b64u.EncodeToString(seq(0xa0, 16))
	plain, err := EnvelopeContenttext(keys, n, now, id)
	if err != nil {
		t.Fatal(err)
	}
	env, err := sealEnvelope(keys, n, now, id, seq(0x80, 12))
	if err != nil {
		t.Fatal(err)
	}
	v.Call.Now, v.Call.Invite, v.Call.Exp = now.Unix(), n.Call.ID, exp.Unix()
	v.Call.Name, v.Call.Session = n.Title, n.SessionID
	v.Call.Plaintext = strings.TrimRight(string(plain), " ")
	v.Call.Envelope = env
	return v
}

func TestVoiceVectors(t *testing.T) {
	v := buildVoiceVectors(t)
	got, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	got = append(got, '\n')
	if *updateVectors {
		if err := os.WriteFile(voiceVectorsPath, got, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(voiceVectorsPath)
	if err != nil {
		t.Fatalf("read voice vectors (run with -update-vectors to create): %v", err)
	}
	if string(want) != string(got) {
		t.Fatal("relay/test/voice-vectors.json is stale: regenerate it and update the Android side")
	}
	// The sealed call opens with the device keys and carries the invitation.
	keys, _ := DeriveDeviceKeys(seq(0x00, 32))
	c, err := OpenEnvelope(keys, v.Call.Envelope, time.Unix(v.Call.Now, 0).Add(time.Second))
	if err != nil {
		t.Fatal(err)
	}
	if c.Kind != KindCall || c.Invite != v.Call.Invite || c.Dest != "session" || c.Sess != "sess_1" || c.Exp != v.Call.Exp {
		t.Fatalf("call envelope content = %+v", c)
	}
}
